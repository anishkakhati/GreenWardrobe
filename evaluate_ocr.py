import os
import re
import cv2
import argparse
import zipfile
import numpy as np
import pandas as pd
import easyocr

from pathlib import Path
from jiwer import cer, wer


# ---------------------------------------
# 1. CONFIGURATION
# ---------------------------------------

SUPPORTED_FIBRES = [
    "COTTON", "POLYESTER", "VISCOSE", "ELASTANE",
    "NYLON", "WOOL", "ACRYLIC", "LINEN", "MODAL", "SILK"
]


# ---------------------------------------
# 2. DATASET EXTRACTION
# ---------------------------------------

def extract_dataset(data_dir):

    data_dir = Path(data_dir)

    zip_files = list(data_dir.glob("*.zip"))

    for zip_path in zip_files:
        print("Extracting:", zip_path.name)

        with zipfile.ZipFile(zip_path, "r") as zip_ref:
            zip_ref.extractall(data_dir)

    csv_files = list(data_dir.rglob("labels_metadata.csv"))

    if not csv_files:
        raise FileNotFoundError(
            "labels_metadata.csv was not found."
        )

    return csv_files[0].parent, csv_files[0]


# ---------------------------------------
# 3. IMAGE PREPROCESSING
# ---------------------------------------

def preprocess_image(image_path):

    image = cv2.imread(str(image_path))

    if image is None:
        raise ValueError(f"Cannot read image: {image_path}")

    # Resize
    image = cv2.resize(
        image,
        None,
        fx=1.5,
        fy=1.5,
        interpolation=cv2.INTER_CUBIC
    )

    # Grayscale
    gray = cv2.cvtColor(
        image,
        cv2.COLOR_BGR2GRAY
    )

    # Contrast enhancement
    clahe = cv2.createCLAHE(
        clipLimit=2.0,
        tileGridSize=(8, 8)
    )

    enhanced = clahe.apply(gray)

    # Sharpening
    kernel = np.array([
        [0, -1, 0],
        [-1, 5, -1],
        [0, -1, 0]
    ])

    sharpened = cv2.filter2D(
        enhanced,
        -1,
        kernel
    )

    return sharpened


# ---------------------------------------
# 4. OCR EXTRACTION
# ---------------------------------------

def extract_text(reader, image_path):

    processed = preprocess_image(image_path)

    results = reader.readtext(
        processed,
        detail=1,
        paragraph=False
    )

    # Sort text regions from top to bottom,
    # then left to right.
    results.sort(
        key=lambda item: (
            min(point[1] for point in item[0]),
            min(point[0] for point in item[0])
        )
    )

    predicted_text = " ".join(
        item[1] for item in results
    )

    confidences = [
        item[2] for item in results
    ]

    average_confidence = (
        float(np.mean(confidences))
        if confidences else 0.0
    )

    return predicted_text, average_confidence


# ---------------------------------------
# 5. TEXT NORMALIZATION
# ---------------------------------------

def normalize_text(text):

    text = str(text).upper()

    text = re.sub(r"\s+", " ", text)

    return text.strip()


# ---------------------------------------
# 6. GROUND TRUTH GENERATION
# ---------------------------------------

def build_ground_truth(row):

    fields = [
        row.get("made_in", ""),
        row.get("rn_number", ""),
        row.get("ca_number", ""),
        row.get("composition", "")
    ]

    # Only the first three instructions are
    # printed on the generated label images.
    care = str(row.get("care_instructions", ""))

    instructions = [
        item.strip()
        for item in care.split(";")
        if item.strip()
    ][:3]

    fields.extend(instructions)

    return " ".join(
        str(value)
        for value in fields
        if pd.notna(value) and str(value).strip()
    )


# ---------------------------------------
# 7. COMPOSITION PARSING
# ---------------------------------------

def parse_composition(text):

    text = normalize_text(text)

    composition = {}

    for fibre in SUPPORTED_FIBRES:

        patterns = [
            rf"(\d+(?:\.\d+)?)\s*%\s*{fibre}\b",
            rf"\b{fibre}\s*(\d+(?:\.\d+)?)\s*%"
        ]

        for pattern in patterns:

            matches = re.findall(pattern, text)

            if matches:
                composition[fibre] = [
                    float(value)
                    for value in matches
                ]

    return composition


# ---------------------------------------
# 8. COMPOSITION EVALUATION
# ---------------------------------------

def evaluate_composition(actual, predicted):

    actual_comp = parse_composition(actual)
    predicted_comp = parse_composition(predicted)

    actual_names = set(actual_comp.keys())
    predicted_names = set(predicted_comp.keys())

    name_correct = (
        actual_names == predicted_names
    )

    percentage_correct = (
        actual_comp == predicted_comp
    )

    exact_correct = (
        percentage_correct and name_correct
    )

    return {
        "fibre_name_match": name_correct,
        "percentage_match": percentage_correct,
        "composition_exact_match": exact_correct,
        "actual_composition": str(actual_comp),
        "predicted_composition": str(predicted_comp)
    }


# ---------------------------------------
# 9. FIELD MATCHING
# ---------------------------------------

def field_match(predicted, expected):

    predicted = normalize_text(predicted)
    expected = normalize_text(expected)

    if not expected:
        return True

    return expected in predicted


# ---------------------------------------
# 10. MAIN EVALUATION
# ---------------------------------------

def run_evaluation(data_dir, output_dir, gpu):

    data_dir = Path(data_dir)
    output_dir = Path(output_dir)

    output_dir.mkdir(
        parents=True,
        exist_ok=True
    )

    image_dir, csv_path = extract_dataset(data_dir)

    df = pd.read_csv(csv_path)

    required_columns = [
        "image",
        "made_in",
        "rn_number",
        "ca_number",
        "composition",
        "care_instructions"
    ]

    missing = [
        column for column in required_columns
        if column not in df.columns
    ]

    if missing:
        raise ValueError(
            f"Missing CSV columns: {missing}"
        )

    print("Total metadata rows:", len(df))

    # GPU setting
    use_gpu = (
        True if gpu == "true"
        else False if gpu == "false"
        else None
    )

    print("Initializing EasyOCR...")

    reader = easyocr.Reader(
        ["en"],
        gpu=use_gpu
    )

    records = []

    # -----------------------------------
    # PROCESS EVERY IMAGE
    # -----------------------------------

    for index, row in df.iterrows():

        image_path = image_dir / str(row["image"])

        if not image_path.exists():
            print("Missing image:", image_path)
            continue

        print(
            f"Processing {index + 1}/{len(df)}:",
            image_path.name
        )

        try:

            predicted, confidence = extract_text(
                reader,
                image_path
            )

            actual = build_ground_truth(row)

            normalized_actual = normalize_text(actual)
            normalized_predicted = normalize_text(predicted)

            composition_result = evaluate_composition(
                row["composition"],
                predicted
            )

            record = {
                "image": image_path.name,
                "actual_text": actual,
                "predicted_text": predicted,
                "ocr_confidence": confidence,

                "full_text_exact_match": (
                    normalized_actual ==
                    normalized_predicted
                ),

                "country_match": field_match(
                    predicted,
                    row["made_in"]
                ),

                "rn_match": field_match(
                    predicted,
                    row["rn_number"]
                ),

                "ca_match": field_match(
                    predicted,
                    row["ca_number"]
                ),

                **composition_result
            }

            records.append(record)

        except Exception as error:

            print("Error:", error)

            records.append({
                "image": image_path.name,
                "actual_text": build_ground_truth(row),
                "predicted_text": "",
                "ocr_confidence": 0.0,
                "full_text_exact_match": False,
                "country_match": False,
                "rn_match": False,
                "ca_match": False,
                "fibre_name_match": False,
                "percentage_match": False,
                "composition_exact_match": False,
                "actual_composition": "",
                "predicted_composition": "",
                "error": str(error)
            })

    results_df = pd.DataFrame(records)

    # -----------------------------------
    # TEXT METRICS
    # -----------------------------------

    valid = results_df[
        results_df["actual_text"].notna()
    ]

    actual_texts = [
        normalize_text(x)
        for x in valid["actual_text"]
    ]

    predicted_texts = [
        normalize_text(x)
        for x in valid["predicted_text"]
    ]

    if actual_texts:

        character_error_rate = cer(
            actual_texts,
            predicted_texts
        )

        word_error_rate = wer(
            actual_texts,
            predicted_texts
        )

    else:

        character_error_rate = 0.0
        word_error_rate = 0.0

    # -----------------------------------
    # ACCURACY SUMMARY
    # -----------------------------------

    def accuracy(column):

        if len(results_df) == 0:
            return 0.0

        return (
            results_df[column].fillna(False).astype(bool).mean()
            * 100
        )

    summary = pd.DataFrame([
        {
            "metric": "Images processed",
            "value": len(results_df)
        },
        {
            "metric": "Character Error Rate",
            "value": character_error_rate
        },
        {
            "metric": "Word Error Rate",
            "value": word_error_rate
        },
        {
            "metric": "Full Text Exact Match (%)",
            "value": accuracy("full_text_exact_match")
        },
        {
            "metric": "Fibre Name Accuracy (%)",
            "value": accuracy("fibre_name_match")
        },
        {
            "metric": "Percentage Accuracy (%)",
            "value": accuracy("percentage_match")
        },
        {
            "metric": "Composition Exact Match (%)",
            "value": accuracy("composition_exact_match")
        },
        {
            "metric": "Country Match (%)",
            "value": accuracy("country_match")
        },
        {
            "metric": "RN Match (%)",
            "value": accuracy("rn_match")
        },
        {
            "metric": "CA Match (%)",
            "value": accuracy("ca_match")
        }
    ])

    # -----------------------------------
    # SAVE REPORTS
    # -----------------------------------

    results_path = output_dir / "all_ocr_results.csv"

    incorrect_path = (
        output_dir / "incorrect_predictions.csv"
    )

    summary_path = (
        output_dir / "accuracy_summary.csv"
    )

    results_df.to_csv(
        results_path,
        index=False
    )

    incorrect = results_df[
        ~(
            results_df["full_text_exact_match"]
            & results_df["composition_exact_match"]
        )
    ]

    incorrect.to_csv(
        incorrect_path,
        index=False
    )

    summary.to_csv(
        summary_path,
        index=False
    )

    print("\n========== EVALUATION SUMMARY ==========")

    print(summary.to_string(index=False))

    print("\nReports saved in:", output_dir)


# ---------------------------------------
# 11. COMMAND LINE
# ---------------------------------------

if __name__ == "__main__":

    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--data-dir",
        default="data"
    )

    parser.add_argument(
        "--output-dir",
        default="outputs"
    )

    parser.add_argument(
        "--gpu",
        choices=["auto", "true", "false"],
        default="auto"
    )

    args = parser.parse_args()

    run_evaluation(
        args.data_dir,
        args.output_dir,
        args.gpu
    )